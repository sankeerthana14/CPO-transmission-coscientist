from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field


# ============================================================
# ALLOWED OUTPUT LABELS
# ============================================================

Mechanism = Literal[
    "PATIENT_ASSOCIATED_CLONAL",
    "ENVIRONMENT_ASSOCIATED_CLONAL",
    "PATIENT_ASSOCIATED_PLASMID",
    "ENVIRONMENT_ASSOCIATED_PLASMID",
    "MIXED",
    "NO_DIRECT_WGS_LINK",
    "UNRESOLVED_NO_TARGET_WGS",
]


Confidence = Literal[
    "high",
    "moderate",
    "low",
    "unresolved",
]


CriticVerdict = Literal[
    "SUPPORTED",
    "SUPPORTED_WITH_REVISIONS",
    "INSUFFICIENT",
]


# ============================================================
# INVESTIGATOR OUTPUT
# ============================================================


class InvestigationReport(BaseModel):
    """
    Structured final report generated by the Investigator.
    """

    target_id: str

    mechanism: Mechanism

    confidence: Confidence

    headline: str = Field(
        description=(
            "One concise sentence summarising the most "
            "defensible transmission/circulation hypothesis."
        )
    )

    key_evidence: list[str] = Field(
        description=(
            "Observed evidence supporting the conclusion. "
            "Keep observations separate from interpretation."
        )
    )

    model_ranking_interpretation: str = Field(
        description=(
            "Interpret the XGBoost ranking as prioritisation "
            "evidence only, not as probability of transmission."
        )
    )

    alternative_explanations: list[str] = Field(
        description=(
            "Plausible alternative explanations such as "
            "persistent reservoir, intermediate hosts, "
            "or unsampled transmission."
        )
    )

    limitations: list[str]

    direct_transmission_proven: bool = Field(
        description=(
            "Should normally be False. WGS relatedness alone "
            "does not prove direct donor-to-recipient transfer."
        )
    )

    conclusion: str = Field(
        description=(
            "Scientifically conservative final interpretation."
        )
    )


# ============================================================
# CRITIC OUTPUT
# ============================================================


class CritiqueReport(BaseModel):
    """
    Structured independent audit of an Investigator report.
    """

    target_id: str

    verdict: CriticVerdict

    chronology_issue: bool

    wgs_interpretation_issue: bool

    model_overreach_issue: bool

    causal_overclaim_issue: bool

    issues: list[str]

    required_revisions: list[str]

    recommended_mechanism: Mechanism

    revised_conclusion: str